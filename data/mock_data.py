# ---- 生成函数 ----
def generate_articles(n_days: int = 30) -> list[dict]:
    """基于模板生成带有真实日期的文章列表"""
    articles = []
    today = datetime.now()

    for i, template in enumerate(ARTICLES):
        days_ago = random.randint(0, n_days)
        pub_date = today - timedelta(days=days_ago)

        # 在模板基础上生成历史评分（模拟趋势）
        score = (
            template["social_heat"] * 0.30
            + template["industry_impact"] * 0.25
            + template["content_quality"] * 0.20
            + template["trend_velocity"] * 0.15
            + template["exclusivity"] * 0.10
        )

        # 生成评分历史（过去7天）
        score_history = []
        for d in range(7, -1, -1):
            noise = random.uniform(-3, 3)
            hist_score = min(100, max(0, score - template["trend_velocity"] * 0.05 * d + noise))
            score_history.append({
                "date": (pub_date - timedelta(days=7 - d)).strftime("%m-%d"),
                "score": round(hist_score, 1),
            })

        article = {
            "id": f"art_{i:03d}",
            "title_en": template["title_en"],
            "title_cn": template["title_cn"],
            "source": template["source"],
            "author": template["author"],
            "url": f"https://example.com/article/{i:03d}",
            "image_url": f"https://picsum.photos/seed/fashion{i}/400/300",
            "published_date": pub_date.strftime("%Y-%m-%d"),
            "category": template["category"],
            "brands": template["brands"],
            "tags": template["tags"],
            "summary_cn": template["summary_cn"],
            "social_heat": template["social_heat"],
            "industry_impact": template["industry_impact"],
            "content_quality": template["content_quality"],
            "trend_velocity": template["trend_velocity"],
            "exclusivity": template["exclusivity"],
            "fashion_score": round(score, 1),
            "score_history": score_history,
            "is_trending": template["is_trending"],
            "trend_direction": template["trend_direction"],
        }
        articles.append(article)

    return sorted(articles, key=lambda x: x["published_date"], reverse=True)


def save_articles(
    path: str = None, n_days: int = 30
) -> list[dict]:
    """生成并保存文章数据到 JSON 文件"""
    if path is None:
        path = Path(__file__).parent / "articles.json"
    articles = generate_articles(n_days)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(articles, f, ensure_ascii=False, indent=2)
    return articles


